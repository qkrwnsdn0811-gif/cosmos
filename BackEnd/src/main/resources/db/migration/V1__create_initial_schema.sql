    ON stock_price_history (company_id, interval_type, trading_at DESC);

-- 수집 파이프라인 운영 조회
CREATE INDEX ix_collection_run_started ON collection_run (started_at DESC);
CREATE INDEX ix_failure_record_run_occurred
    ON failure_record (run_id, occurred_at DESC);
CREATE INDEX ix_failure_record_resolution_occurred
    ON failure_record (resolution_status, occurred_at DESC);
CREATE INDEX ix_data_asset_run ON data_asset (run_id);
